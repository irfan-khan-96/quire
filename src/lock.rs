//! `quire.lock`: the exact revision of every git dependency.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

pub const LOCK_NAME: &str = "quire.lock";
const LOCK_VERSION: u32 = 1;
const HEADER: &str = "# This file is generated by quire. Do not edit it by hand.\n";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    #[serde(default, rename = "package", skip_serializing_if = "Vec::is_empty")]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    /// e.g. `git+https://github.com/org/repo?tag=v1.0`
    pub source: String,
    /// Full commit hash.
    pub rev: String,
}

impl Default for Lockfile {
    fn default() -> Self {
        Lockfile { version: LOCK_VERSION, packages: Vec::new() }
    }
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Lockfile> {
        if !path.exists() {
            return Ok(Lockfile::default());
        }
        let text = fs::read_to_string(path).with_context(|| format!("failed to read `{}`", path.display()))?;
        let lock: Lockfile = toml::from_str(&text)
            .with_context(|| format!("failed to parse `{}`; delete it to regenerate", path.display()))?;
        if lock.version != LOCK_VERSION {
            bail!(
                "`{}` has version {}, but this quire understands version {LOCK_VERSION}",
                path.display(),
                lock.version
            );
        }
        Ok(lock)
    }

    pub fn find(&self, name: &str, source: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name && p.source == source)
    }

    pub fn render(&self) -> String {
        let mut sorted = self.clone();
        sorted.packages.sort();
        format!("{HEADER}{}", toml::to_string(&sorted).expect("lockfile serializes"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_sorted() {
        let lock = Lockfile {
            version: 1,
            packages: vec![
                LockedPackage { name: "b".into(), source: "git+u2".into(), rev: "2".repeat(40) },
                LockedPackage { name: "a".into(), source: "git+u1?tag=v1".into(), rev: "1".repeat(40) },
            ],
        };
        let text = lock.render();
        assert!(text.starts_with(HEADER));
        assert!(text.find("name = \"a\"").unwrap() < text.find("name = \"b\"").unwrap());
        let parsed: Lockfile = toml::from_str(&text).unwrap();
        assert_eq!(parsed.find("a", "git+u1?tag=v1").unwrap().rev, "1".repeat(40));
        assert!(parsed.find("a", "git+u1").is_none());
    }
}
