#!/usr/bin/env python3
"""Write the Homebrew formula and the Scoop manifest for a release.

    python3 packaging/render.py v0.1.2 dist/ out/

reads the `<archive>.sha256` files that the release workflow puts in `dist/`
and writes `out/Formula/quire.rb` and `out/bucket/quire.json`, laid out like
the tap and bucket repositories they are copied into.
"""

import json
import sys
from pathlib import Path

REPO = "https://github.com/irfan-khan-96/quire"
DESCRIPTION = "Cargo-like build tool and package manager for LaTeX"
HOMEPAGE = "https://irfan-khan-96.github.io/quire/"


def checksums(dist: Path) -> dict[str, str]:
    sums = {}
    for file in dist.glob("*.sha256"):
        digest, name = file.read_text().split()[:2]
        sums[name.lstrip("*")] = digest
    return sums


def formula(version: str, sums: dict[str, str]) -> str:
    def asset(target: str) -> str:
        name = f"quire-{target}.tar.gz"
        if name not in sums:
            raise SystemExit(f"missing checksum for {name}")
        return f'url "{REPO}/releases/download/v{version}/{name}"\n      sha256 "{sums[name]}"'

    return f'''# Generated by packaging/render.py in {REPO}; do not edit by hand.
class Quire < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      {asset("aarch64-apple-darwin")}
    end
    on_intel do
      {asset("x86_64-apple-darwin")}
    end
  end

  on_linux do
    on_arm do
      {asset("aarch64-unknown-linux-musl")}
    end
    on_intel do
      {asset("x86_64-unknown-linux-musl")}
    end
  end

  def install
    bin.install "quire"
  end

  def caveats
    <<~EOS
      quire drives an existing TeX installation (TeX Live, MacTeX or MiKTeX).
      Run `quire doctor` to check your setup.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/quire --version")
  end
end
'''


def scoop(version: str, sums: dict[str, str]) -> str:
    target = "x86_64-pc-windows-msvc"
    name = f"quire-{target}.zip"
    if name not in sums:
        raise SystemExit(f"missing checksum for {name}")
    manifest = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": HOMEPAGE,
        "license": "MIT|Apache-2.0",
        "notes": "quire drives an existing TeX installation (TeX Live or MiKTeX). Run `quire doctor` to check your setup.",
        "architecture": {
            "64bit": {
                "url": f"{REPO}/releases/download/v{version}/{name}",
                "hash": sums[name],
                "extract_dir": f"quire-{target}",
            }
        },
        "bin": "quire.exe",
        "checkver": "github",
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": f"{REPO}/releases/download/v$version/{name}",
                    "hash": {"url": "$url.sha256"},
                    "extract_dir": f"quire-{target}",
                }
            }
        },
    }
    return json.dumps(manifest, indent=4) + "\n"


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    tag, dist, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    version = tag.removeprefix("v")
    sums = checksums(dist)
    (out / "Formula").mkdir(parents=True, exist_ok=True)
    (out / "bucket").mkdir(parents=True, exist_ok=True)
    (out / "Formula" / "quire.rb").write_text(formula(version, sums))
    (out / "bucket" / "quire.json").write_text(scoop(version, sums))


if __name__ == "__main__":
    main()
